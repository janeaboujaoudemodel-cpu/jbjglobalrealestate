#!/usr/bin/env node
/**
 * Static guard: fails CI if any source file reintroduces a same-tone
 * text-on-background combo (e.g. bg-foreground + text-foreground,
 * bg-[#1A1A1A] + text-[#1A1A1A]).
 *
 * Catches the worst readability bug class: invisible labels.
 */
import { execSync } from "child_process";

// NOTE: `(?!\/)` after each bg/text token excludes alpha-tinted variants
// (e.g. `bg-[#1A1A1A]/5`). `(?<![:\w-])` before each `text-…` token excludes
// state-prefixed swaps (e.g. `hover:text-[#1A1A1A]` paired with a non-ink bg
// on hover). Those represent legitimate hover/focus/data-state inversions,
// not static same-tone bugs.
const PATTERNS = [
  { id: "fg-fg",      re: /(?<![:\w-])bg-foreground(?!\/)[^"'`]*(?<![:\w-])text-foreground(?!\/)/g, msg: "bg-foreground + text-foreground" },
  { id: "primary-primary", re: /(?<![:\w-])bg-primary(?!-foreground)(?!\/)[^"'`]*(?<![:\w-])text-primary(?!-foreground)(?!\/)/g, msg: "bg-primary + text-primary" },
  { id: "ink-ink",    re: /(?<![:\w-])bg-\[#1A1A1A\](?!\/)[^"'`]*(?<![:\w-])text-\[#1A1A1A\](?!\/)/gi, msg: "bg-[#1A1A1A] + text-[#1A1A1A]" },
  { id: "champ-champ", re: /(?<![:\w-])bg-\[#FDFBF7\](?!\/)[^"'`]*(?<![:\w-])text-\[#FDFBF7\](?!\/)/gi, msg: "bg-[#FDFBF7] + text-[#FDFBF7]" },
  { id: "champ-champ-7", re: /(?<![:\w-])bg-\[#F7F2EA\](?!\/)[^"'`]*(?<![:\w-])text-\[#F7F2EA\](?!\/)/gi, msg: "bg-[#F7F2EA] + text-[#F7F2EA]" },
  { id: "black-black", re: /(?<![:\w-])bg-black(?!\/)[^"'`]*(?<![:\w-])text-black(?!\/)/g, msg: "bg-black + text-black" },
  { id: "white-white", re: /(?<![:\w-])bg-white(?!\/)[^"'`]*(?<![:\w-])text-white(?!\/)/g, msg: "bg-white + text-white" },
];

let files = [];
try {
  files = execSync(
    `rg -l --type-add 'tsx:*.{ts,tsx,jsx,js}' -ttsx "bg-(foreground|primary|black|white|\\[#)" src/`,
    { encoding: "utf8" }
  ).trim().split("\n").filter(Boolean);
} catch {
  console.log("✓ Same-tone guard: no candidate files.");
  process.exit(0);
}

const offenders = [];
for (const file of files) {
  const { readFileSync } = await import("fs");
  let content;
  try { content = readFileSync(file, "utf8"); } catch { continue; }
  for (const p of PATTERNS) {
    p.re.lastIndex = 0;
    const matches = content.match(p.re);
    if (matches?.length) {
      offenders.push({ file, pattern: p.msg, count: matches.length, sample: matches[0] });
    }
  }
}

// Aggregate per file (sum across patterns) for baseline comparison.
const perFile = new Map();
for (const o of offenders) {
  perFile.set(o.file, (perFile.get(o.file) ?? 0) + o.count);
}

// --print-baseline: emit current state as JSON the team can commit.
if (process.argv.includes("--print-baseline")) {
  const entries = [...perFile.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([file, count]) => ({ file, count }));
  process.stdout.write(JSON.stringify({
    _comment: "Snapshot generated by check-same-tone.mjs --print-baseline. New files or higher counts block CI.",
    entries,
  }, null, 2) + "\n");
  process.exit(0);
}

// Load baseline (pre-existing tolerated offenders).
let baseline = { entries: [] };
try {
  const { readFileSync } = await import("fs");
  const { fileURLToPath } = await import("url");
  const { dirname, join } = await import("path");
  const here = dirname(fileURLToPath(import.meta.url));
  baseline = JSON.parse(readFileSync(join(here, "same-tone-baseline.json"), "utf8"));
} catch {
  baseline = { entries: [] };
}
const baselineMap = new Map((baseline.entries ?? []).map((e) => [e.file, e.count]));

// Classify: NEW file or COUNT-GROWTH (regression) vs tolerated baseline.
const regressions = [];
const tolerated = [];
for (const [file, count] of perFile.entries()) {
  const allowed = baselineMap.get(file);
  if (allowed === undefined) {
    regressions.push({ file, count, reason: "new file" });
  } else if (count > allowed) {
    regressions.push({ file, count, reason: `count grew ${allowed} → ${count}` });
  } else {
    tolerated.push({ file, count, allowed });
  }
}

if (tolerated.length) {
  console.log(`ⓘ Same-tone baseline: ${tolerated.length} pre-existing file(s) tolerated (see scripts/contrast/same-tone-baseline.json).`);
}

if (regressions.length === 0) {
  console.log("✓ Same-tone guard: no new offenders vs baseline.");
  process.exit(0);
}

console.error("✗ Same-tone guard FAILED — NEW readability regression(s) introduced:");
for (const r of regressions) {
  const samples = offenders.filter((o) => o.file === r.file);
  console.error(`  ${r.file}  [${r.reason}]  (${r.count} hit${r.count === 1 ? "" : "s"})`);
  for (const s of samples) {
    console.error(`     ${s.pattern} (${s.count}x)`);
    console.error(`       sample: ${s.sample}`);
  }
}
console.error("\nFix the new file(s), or — if intentional — refresh the baseline:");
console.error("  node scripts/contrast/check-same-tone.mjs --print-baseline > scripts/contrast/same-tone-baseline.json");
process.exit(1);

