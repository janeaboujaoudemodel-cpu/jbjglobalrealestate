function quick(i: QuickInput): ServiceConfig {
  const L = i.labels ?? {};
  const tocLabels = L.tocLabels ?? [
    "Overview","Performance","Service Scope","Approach","Financials","Operations",
    "Workflow","Reporting","Trust & Governance","Fees","Request a Proposal","Questions",
  ];
  const tocIcons = [Home, BarChart3, ClipboardCheck, Compass, DollarSign, Wrench, Sparkle, FileText, ShieldCheck, Percent, CalendarClock, Headphones];
  const tocIds = ["overview","metrics","services","leasing","finance","operations","workflow","reporting","trust","fees","proposal","faq"];
  return buildConfig({
    slug: i.slug, seoTitle: i.seoTitle, seoDescription: i.seoDescription,
    hero: { eyebrowIcon: i.heroIcon, eyebrow: i.heroLabel, title: i.heroTitle,
      subtitle: i.heroSubtitle, primaryLabel: i.primary, secondaryLabel: i.secondary,
      secondaryHref: `/contact?service=${i.slug}` },
    toc: tocIds.map((id, idx) => ({ id, label: tocLabels[idx], icon: tocIcons[idx] })),
    overview: { eyebrow: "Overview", title: `${i.heroTitle} Overview`, text: i.overviewText,
      leftTitle: i.overviewLeft[0], leftItems: i.overviewLeft[1],
      rightTitle: i.overviewRight[0], rightItems: i.overviewRight[1] },
    metrics: { eyebrow: "Performance", title: L.metricsTitle ?? "Performance Indicators",
      text: "Clear operational indicators keep every engagement measurable and accountable.",
      featureIcon: i.metricFeature[0], featureTitle: i.metricFeature[1], featureText: i.metricFeature[2],
      items: i.metrics.map(([v, l, ic]) => ({ value: v, label: l, icon: ic })) },
    scope: { eyebrow: "Scope", title: L.scopeTitle ?? "Service Scope",
      text: "Every workstream is handled in one client-first system.",
      items: i.scope.map(([t, ic, pts]) => ({ title: t, icon: ic, points: pts })) },
    placement: { eyebrow: "Approach", title: L.placementTitle ?? "Our Approach",
      text: i.placementText, steps: i.placementSteps },
    finance: { eyebrow: "Financials", title: L.financeTitle ?? "Financials & Value",
      text: "Transparent value, clean reporting, and clear ownership of every cost.",
      items: i.financeItems.map(([ic, t, tx]) => ({ icon: ic, title: t, text: tx })) },
    operations: { eyebrow: "Operations", title: L.operationsTitle ?? "Operations & Delivery",
      text: "Every action has an approval path, visible client updates, and clean records.",
      items: i.operationsItems.map(([t, tx]) => ({ title: t, text: tx })) },
    workflow: { eyebrow: "Workflow", title: L.workflowTitle ?? "Engagement Workflow",
      steps: i.workflowSteps.map(([l, ic]) => ({ label: l, icon: ic })) },
    reporting: { eyebrow: "Transparency", title: L.reportingTitle ?? "Reporting & Transparency",
      text: "Structured updates without chasing fragmented information.",
      items: i.reportingItems },
    trust: { eyebrow: "Governance", title: L.trustTitle ?? "Trust & Governance",
      items: i.trustItems.map(([ic, t, tx]) => ({ icon: ic, title: t, text: tx })) },
    fees: { eyebrow: "Fees", title: L.feesTitle ?? "Fees & Structure",
      text: "Fees are confirmed after scope, complexity, and requirements are aligned.",
      items: i.feesItems },
    proposal: { eyebrow: "Proposal", title: L.proposalTitle ?? `Request a ${i.heroTitle} Proposal`,
      text: L.proposalText ?? "Tell us what you need. We'll confirm scope, timing, and the right service path.",
      formTitle: i.formTitle, serviceOptions: i.serviceOptions,
      defaultService: i.serviceOptions[0],
      messagePlaceholder: i.messagePlaceholder,
      formSource: `${i.slug}-proposal`, variant: "consultation" },
    faq: i.faq.map(([q, a]) => ({ q, a })),
    preFooter: { title: i.preFooterTitle, subtitle: i.preFooterSub,
      primaryText: i.primary, secondaryLink: "/contact", secondaryText: "Speak With Our Team" },
  });
}

